local t = require('minitest')
local version = require('/lua/ge/extensions/beamRemotePlus/version')

t.describe('version: parse', function()
  t.it('reads the release numbers, with or without v and suffix', function()
    t.assertEquals(table.concat(version.parse('0.0.4'), '.'), '0.0.4')
    t.assertEquals(table.concat(version.parse('v0.0.4-0.39'), '.'), '0.0.4')
    t.assertEquals(table.concat(version.parse('0.0.4-delta'), '.'), '0.0.4')
    t.assertEquals(table.concat(version.parse('1.12.3-0.39'), '.'), '1.12.3')
  end)
  t.it('rejects what is not a release number', function()
    t.assertNil(version.parse('PoC'))
    t.assertNil(version.parse(''))
    t.assertNil(version.parse(nil))
    t.assertNil(version.parse(42))
  end)
end)

t.describe('version: compare', function()
  t.it('orders releases number by number', function()
    t.assertEquals(version.compare('0.0.3', '0.0.4'), -1)
    t.assertEquals(version.compare('0.1.0', '0.0.9'), 1)
    t.assertEquals(version.compare('0.0.10', '0.0.9'), 1)
    t.assertEquals(version.compare('1.0.0', '0.99.99'), 1)
  end)
  t.it('ignores the suffix', function()
    t.assertEquals(version.compare('0.0.4-0.39', '0.0.4'), 0)
    t.assertEquals(version.compare('0.0.4-0.39', '0.0.4-0.40'), 0)
  end)
  t.it('cannot compare an unknown version', function()
    t.assertNil(version.compare('PoC', '0.0.4'))
    t.assertNil(version.compare('0.0.4', nil))
  end)
end)

t.describe('version: outdated', function()
  t.it('names the older side', function()
    t.assertEquals(version.outdated('0.0.5', '0.0.4'), 'app')
    t.assertEquals(version.outdated('0.0.4', '0.0.5'), 'mod')
  end)
  t.it('nothing when they match or one side is unknown', function()
    t.assertNil(version.outdated('0.0.4-0.39', '0.0.4'))
    t.assertNil(version.outdated('0.0.4', nil))
  end)
end)
