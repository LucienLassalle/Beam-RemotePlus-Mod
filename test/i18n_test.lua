local t = require('minitest')
local i18n = require('/lua/ge/extensions/beamRemotePlus/i18n')

t.describe('i18n', function()
  t.it('uses the game translation when available', function()
    local tr = i18n.new(function(key) return key == 'beamRemotePlus.toast.enabled' and 'Activé' or key end)
    t.assertEquals(tr.t('beamRemotePlus.toast.enabled'), 'Activé')
  end)
  t.it('falls back to English when the game returns the key itself', function()
    local tr = i18n.new(function(key) return key end)
    t.assertEquals(tr.t('beamRemotePlus.toast.enabled'), 'Phone connections enabled')
  end)
  t.it('falls back when the translation system is not ready', function()
    t.assertEquals(i18n.new(false).t('beamRemotePlus.toast.title'), 'Beam-RemotePlus')
    t.assertEquals(i18n.new(function() error('boom') end).t('beamRemotePlus.toast.title'), 'Beam-RemotePlus')
  end)
  t.it('fills placeholders and keeps unknown ones visible', function()
    t.assertEquals(i18n.format('{a} and {b}', { a = 1 }), '1 and {b}')
    t.assertContains(i18n.new(nil).t('beamRemotePlus.toast.pairingCode', { code = '12345' }), '12345')
  end)
  t.it('returns the key for unknown entries', function()
    t.assertEquals(i18n.new(nil).t('nope'), 'nope')
  end)
end)
