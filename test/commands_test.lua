local t = require('minitest')
local fakes = require('fakes')
local commandsModule = require('/lua/ge/extensions/beamRemotePlus/commands')

local function setup(opts)
  opts = opts or {}
  local vehicle = fakes.vehicle(7)
  local calls = {}
  local commands = commandsModule.new({
    getVehicle = function(player) calls.player = player return not opts.noVehicle and vehicle or nil end,
    switchVehicle = function(player, dir) calls.switch = dir return true end,
    cycleCamera = function(player, offset) calls.camera = offset return true end,
    setPov = opts.pov and function(_, quality, options)
      calls.pov, calls.povOptions = quality, options
      return true
    end or nil,
    cyclePovCamera = opts.pov and function(_, offset)
      if not opts.video then return nil end
      calls.povCamera = offset
      return true
    end or nil,
    pulseButton = function(_, button) calls.button = button end,
    buttons = { shiftUp = 0, shiftDown = 1 },
    requestActions = function() calls.requested = true return true end,
    runVehicleAction = function(_, name, value)
      calls.vehicleAction = (calls.vehicleAction or '') .. name .. '=' .. value .. ';'
      return true
    end,
  })
  local client = { player = 1, holds = {}, debug = false }
  return commands, client, vehicle, calls
end

t.describe('commands: hold actions', function()
  t.it('horn on/off runs the native horn code on the player vehicle', function()
    local commands, client, vehicle, calls = setup()
    t.assertTrue(commands.execute(client, 'horn', '1'))
    t.assertContains(vehicle.commands[1], 'electrics.horn(true)')
    t.assertTrue(client.holds.horn)
    t.assertEquals(calls.player, 1)
    t.assertTrue(commands.execute(client, 'horn', '0'))
    t.assertContains(vehicle.commands[2], 'electrics.horn(false)')
    t.assertNil(client.holds.horn)
  end)
  t.it('high beams stay on while held (native flash action)', function()
    local commands, client, vehicle = setup()
    commands.execute(client, 'highbeam', '1')
    t.assertContains(vehicle.commands[1], 'light_flash_highbeams(true)')
  end)
  t.it('rejects a hold without on/off argument', function()
    local commands, client = setup()
    local ok, err = commands.execute(client, 'horn')
    t.assertFalse(ok)
    t.assertEquals(err, commandsModule.ERR_BAD_ARGUMENT)
  end)
  t.it('release() turns a hold off', function()
    local commands, client, vehicle = setup()
    commands.release(client, 'horn')
    t.assertContains(vehicle.commands[1], 'electrics.horn(false)')
  end)
  t.it('keeps protocol v1 recover names working', function()
    local commands, client, vehicle = setup()
    local ok, _, name = commands.execute(client, 'recover_start')
    t.assertTrue(ok)
    t.assertEquals(name, 'recover')
    t.assertContains(vehicle.commands[1], 'startRecovering')
  end)
  t.it('recovers like the Insert key, for the player of the phone', function()
    local commands, client, vehicle = setup()
    commands.execute(client, 'recover', '1')
    t.assertContains(vehicle.commands[1], 'extensions.hook("trackVehReset", \' .. obj:getId()')
    commands.execute(client, 'recover', '0')
    t.assertContains(vehicle.commands[2], 'recovery.stopRecovering(1)')
  end)
end)

