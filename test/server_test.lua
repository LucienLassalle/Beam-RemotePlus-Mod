t.describe('server: point of view video', function()
  local function povMessages(env)
    local list = {}
    for _, s in ipairs(env.transport.sent) do
      if s.payload:find('"type":"pov"', 1, true) then list[#list + 1] = s.payload end
    end
    return list
  end
  t.it('streams the view of the phone player once asked, until it stops', function()
    local env = setup({ pov = true })
    connect(env)
    local client = env.server.clients.get('10.0.0.2')
    env.server.onInputBindingsChanged({ ['vinput' .. client.deviceInst] = 0 })
    env.transport.push('cmd|pov|1', '10.0.0.2')
    env.server.update()
    t.assertEquals(env.povUrl, 'udp://10.0.0.2:4448?pkt_size=1316')
    env.clock.advance(300)
    env.server.update()
    local told = povMessages(env)
    t.assertContains(told[1], '"state":"starting"')
    t.assertContains(told[#told], '"state":"live"')
    t.assertContains(told[#told], '"inside":true')
    env.transport.push('cmd|pov|0', '10.0.0.2')
    env.server.update()
    t.assertEquals(env.povDestroyed, 1)
  end)
  t.it('is offered only when the game can do it', function()
    local function offered(env)
      connect(env)
      env.server.onInputBindingsChanged({ ['vinput' .. env.server.clients.get('10.0.0.2').deviceInst] = 0 })
      for _, s in ipairs(env.transport.sent) do
        if s.payload:find('"type":"session"', 1, true) then return s.payload:find('"pov"', 1, true) ~= nil end
      end
    end
    t.assertTrue(offered(setup({ pov = true })))
    t.assertFalse(offered(setup()))
  end)
  t.it('changes quality, and the camera buttons change the camera of the video', function()
    local env = setup({ pov = true })
    connect(env)
    env.server.onInputBindingsChanged({ ['vinput' .. env.server.clients.get('10.0.0.2').deviceInst] = 0 })
    env.transport.push('cmd|pov|1080p30', '10.0.0.2')
    env.server.update()
    t.assertEquals(env.povWidth, 1920)
    env.transport.push('cmd|cam_next', '10.0.0.2')
    env.server.update()
    t.assertEquals(env.povCamera, 1)
  end)
  t.it('renders the video in the shape of the phone screen, at its bitrate', function()
    local env = setup({ pov = true })
    connect(env)
    env.server.onInputBindingsChanged({ ['vinput' .. env.server.clients.get('10.0.0.2').deviceInst] = 0 })
    env.transport.push('cmd|pov|720p60|1424x640|high', '10.0.0.2')
    env.server.update()
    t.assertEquals(env.povWidth, 1424)
    t.assertEquals(env.povHeight, 640)
    t.assertEquals(env.povBitrate, 12000000)
  end)
  t.it('turns the camera of the video and switches the free camera', function()
    local env = setup({ pov = true })
    connect(env)
    env.server.onInputBindingsChanged({ ['vinput' .. env.server.clients.get('10.0.0.2').deviceInst] = 0 })
    env.transport.push('cmd|pov|1', '10.0.0.2')
    env.transport.push('cmd|look|7|-2', '10.0.0.2')
    env.transport.push('cmd|freecam|1', '10.0.0.2')
    env.server.update()
    t.assertEquals(env.povLook[1], 7)
    t.assertEquals(env.povLook[2], -2)
    t.assertTrue(env.povFree)
  end)
  t.it('tells the phone why there is no video', function()
    local env = setup({ pov = true, noEncoder = true })
    connect(env)
    env.server.onInputBindingsChanged({ ['vinput' .. env.server.clients.get('10.0.0.2').deviceInst] = 0 })
    env.transport.push('cmd|pov|1', '10.0.0.2')
    env.server.update()
    local told = povMessages(env)
    t.assertContains(told[1], '"state":"error"')
    t.assertContains(told[1], '"error":"encoder"')
  end)
  t.it('frees the views when the mod stops', function()
    local env = setup({ pov = true })
    connect(env)
    env.server.onInputBindingsChanged({ ['vinput' .. env.server.clients.get('10.0.0.2').deviceInst] = 0 })
    env.transport.push('cmd|pov|1', '10.0.0.2')
    env.server.update()
    env.server.shutdown()
    t.assertEquals(env.povDestroyed, 1)
  end)
end)

