t.describe('server: lock', function()
  t.it('is unlocked on start, whatever was saved', function()
    local env = setup({ files = { [configModule.FILE_PATH] = { locked = true } } })
    env.server.update()
    t.assertFalse(env.server.isLocked())
  end)
  t.it('refuses new phones but keeps connected ones driving', function()
