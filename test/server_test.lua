t.describe('server: timeouts and players', function()
  t.it('disconnects silent phones and tells the player', function()
    local env = setup()
    connect(env)
    env.clock.advance(protocol.CLIENT_TIMEOUT_MS + 1)
    env.server.update()
    t.assertEquals(env.server.clients.count(), 0)
    t.assertContains(env.toasts[#env.toasts].text, 'Pixel')
  end)
  -- A driving phone assigned to player 1, whose car sends telemetry.
  local function driving(env, motion)
    connect(env)
    local client = env.server.clients.get('10.0.0.2')
    env.server.onInputBindingsChanged({ ['vinput' .. client.deviceInst] = 0 })
    env.transport.push(protocol.encodeControlPacket(0.5, 1, 0), '10.0.0.2')
    env.server.update()
    env.server.onTelemetry(11, motion)
  end
  local function handbrakeCalls(env, on)
    local n = 0
    for _, code in ipairs(env.vehicle.commands) do if code == serverModule.handbrakeCode(on) then n = n + 1 end end
    return n
  end

  t.it('brakes the moving car of a silent phone before it times out', function()
    local env = setup()
    driving(env, { airspeed = 20, gearIndex = 3, gearboxMode = 'arcade' })
    env.clock.advance(protocol.SIGNAL_LOST_MS + 1)
    env.server.update()
    t.assertEquals(env.input.emitted[#env.input.emitted].value, protocol.STOP_BRAKE)
    t.assertEquals(env.server.clients.count(), 1)
  end)
  t.it('holds the stopped car of a silent phone with the handbrake, not the brake', function()
    local env = setup()
    driving(env, { airspeed = 0, gearIndex = 1, gearboxMode = 'arcade' })
    env.clock.advance(protocol.SIGNAL_LOST_MS + 1)
    env.server.update()
    t.assertEquals(handbrakeCalls(env, true), 1)
    t.assertEquals(env.input.emitted[#env.input.emitted].value, 0)
    env.transport.push(protocol.encodeControlPacket(0.5, 0.4, 0), '10.0.0.2')
    env.server.update()
    t.assertEquals(handbrakeCalls(env, false), 1, 'released when the phone is back')
  end)
  t.it('stops the car of a phone that leaves, then tells the player it is gone', function()
    local env = setup()
    driving(env, { airspeed = 15, gearIndex = 2 })
    env.transport.push('cmd|leave', '10.0.0.2')
    env.server.update()
    env.server.update() -- the watchdog brakes from the next frame
    t.assertEquals(env.input.emitted[#env.input.emitted].value, protocol.STOP_BRAKE)
    t.assertEquals(env.server.clients.count(), 1)
    t.assertNil(env.transport.lastTo('10.0.0.2'):find('"type":"ack"', 1, true))
    env.server.onTelemetry(11, { airspeed = 0.2, gearIndex = 2 })
    env.clock.advance(1500)
    env.server.update()
    t.assertEquals(handbrakeCalls(env, true), 1)
    t.assertEquals(env.server.clients.count(), 0)
    t.assertContains(env.toasts[#env.toasts].text, 'Pixel')
  end)
  t.it('reads the motion of a car from its telemetry', function()
    local m = serverModule.motionOf({ airspeed = -3, gear = 'R', gearboxMode = 'arcade' })
    t.assertEquals(m.speed, 3)
    t.assertTrue(m.reverse)
    t.assertTrue(m.arcade)
    t.assertNil(serverModule.motionOf({ rpm = 900 }))
  end)
  t.it('assigns players and routes telemetry to the right phone', function()
    local env = setup()
    connect(env)
    local client = env.server.clients.get('10.0.0.2')
    env.server.onInputBindingsChanged({ ['vinput' .. client.deviceInst] = 0 })
    env.server.update()
    t.assertEquals(env.server.onTelemetry(11, { rpm = 1234 }), 1)
    t.assertContains(env.transport.lastTo('10.0.0.2'), '"rpm":1234')
  end)
end)

