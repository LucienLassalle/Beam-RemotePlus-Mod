    env.transport.push(protocol.encodeControlPacket(0.5, 1, 0), '10.0.0.2')
    env.server.update()
    t.assertTrue(#env.input.emitted > 0)
  end)
  t.it('does not hand the pairing code out while locked', function()
    local env = setup()
    env.server.setLocked(true)
    env.transport.push(protocol.DISCOVER_MESSAGE, '10.0.0.9')
    env.server.update()
    t.assertNil(env.transport.lastTo('10.0.0.9'))
  end)
  t.it('accepts new phones again once unlocked', function()
    local env = setup()
    env.server.setLocked(true)
    env.server.setLocked(false)
    connect(env, '10.0.0.3')
    t.assertEquals(env.server.clients.count(), 1)
  end)
end)

