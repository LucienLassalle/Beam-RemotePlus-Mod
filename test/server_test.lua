local t = require('minitest')
local fakes = require('fakes')
local serverModule = require('/lua/ge/extensions/beamRemotePlus/server')
local configModule = require('/lua/ge/extensions/beamRemotePlus/config')
local i18nModule = require('/lua/ge/extensions/beamRemotePlus/i18n')
local protocol = require('/lua/ge/extensions/beamRemotePlus/protocol')

local CODE = '20367'

local function setup(opts)
  opts = opts or {}
  local env = {
    transport = fakes.transport(),
    input = fakes.input(),
    clock = fakes.clock(),
    files = fakes.memoryFiles(opts.files),
    toasts = {},
    states = {},
    vehicle = fakes.vehicle(11),
    rescans = 0,
    mods = opts.mods or {}, -- core_modmanager.getMods()
  }
  env.transport.failOpen = opts.portBusy
  env.native = { isOpen = false, locked = false, lockCalls = 0 }
  function env.native.open() env.native.isOpen = true return true end
  function env.native.setLocked(value)
    env.native.lockCalls = env.native.lockCalls + 1
    if opts.nativeCannotLock and value then return false end
    env.native.locked = value
    return true
  end
  local config = configModule.new(env.files)
  config.load()
  local logger, logLines = fakes.logger()
  env.logLines = logLines.lines
  env.server = serverModule.new({
    transport = env.transport,
    input = env.input,
    config = config,
    i18n = i18nModule.new(nil),
    logger = logger,
    clock = env.clock.fn,
    notify = function(text, kind) env.toasts[#env.toasts + 1] = { text = text, kind = kind } end,
    publishState = function(state) env.states[#env.states + 1] = state end,
    getSecurityCode = function() if opts.noCode then return nil end return CODE end,
    getHostLabel = function() return "Test's PC" end,
    getHostAddress = function() return '192.168.1.20' end,
    playerColor = function(player) return (env.colors or { '#f21a1a', '#2673ff' })[player + 1] end,
    getVehicle = function() return env.vehicle end,
    switchVehicle = function() return true end,
    cycleCamera = function() return true end,
    onDeviceCreated = function() env.rescans = env.rescans + 1 end,
    joinPlayer = function(client)
      env.joins = (env.joins or 0) + 1
      if opts.cannotJoin then return false, 'setup_open' end
      env.server.onInputBindingsChanged({ ['vinput' .. client.deviceInst] = 1 })
      return true
    end,
    nativeRemote = env.native,
    povViews = opts.pov and {
      createView = function(id, player, w, h)
        env.povWidth, env.povHeight = w, h
        return { id = id, player = player }
      end,
      destroyView = function() env.povDestroyed = (env.povDestroyed or 0) + 1 end,
      startOutput = function(_, url, _, bitrate)
        if opts.noEncoder then return nil, 'no_output' end
        env.povUrl, env.povBitrate = url, bitrate
        return 1
      end,
      stopOutput = function() end,
      outputStatus = function() return 0 end,
      update = function() return true end,
      cycleCamera = function(_, offset) env.povCamera = offset return true end,
      look = function(_, dx, dy) env.povLook = { dx, dy } end,
      resetCamera = function() end,
      setFree = function() env.povFree = true return true end,
      fly = function() end,
    } or nil,
    getMods = function() return env.mods end,
    fileExists = function() return false end,
  })
  return env
end

local function connect(env, ip, version)
  env.transport.push(protocol.buildPingMessage(CODE, version or 2, 'Pixel'), ip or '10.0.0.2')
  env.server.update()
end

t.describe('server: listening', function()
  t.it('listens by default on the first frame', function()
    local env = setup()
    env.server.update()
    t.assertTrue(env.server.isListening())
    t.assertTrue(env.transport.opened)
  end)
  t.it('shows the pairing code once', function()
    local env = setup()
    env.server.update()
    env.server.update()
    local codeToasts = 0
    for _, toast in ipairs(env.toasts) do if toast.text:find(CODE, 1, true) then codeToasts = codeToasts + 1 end end
    t.assertEquals(codeToasts, 1)
  end)
  t.it('listens even if an older version saved enabled = false', function()
    local env = setup({ files = { [configModule.FILE_PATH] = { enabled = false } } })
    env.server.update()
    t.assertTrue(env.server.isListening())
  end)
  t.it('shutting down drops phones, releases holds and closes the port', function()
    local env = setup()
    connect(env)
    env.transport.push('cmd|horn|1', '10.0.0.2')
    env.server.update()
    env.server.shutdown()
    t.assertFalse(env.transport.opened)
    t.assertEquals(env.server.clients.count(), 0)
    t.assertContains(env.vehicle.commands[#env.vehicle.commands], 'electrics.horn(false)')
  end)
  t.it('retries quietly when the port is busy', function()
    local env = setup({ portBusy = true })
    env.server.update()
    env.server.update()
    t.assertFalse(env.server.isListening())
  end)
end)

