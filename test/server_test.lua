    env.transport.push('cmd|horn|1', '10.0.0.7')
    env.server.update()
    t.assertEquals(#env.input.emitted, 0)
    t.assertContains(env.transport.lastTo('10.0.0.7'), '"error":"display_only"')
  end)
  t.it('a display phone may ask for the vehicle skeleton', function()
    local env = setup()
    env.transport.push(protocol.buildPingMessage(CODE, 2, 'Tablet', 'display'), '10.0.0.7')
    env.server.update()
    env.transport.push('cmd|skeleton', '10.0.0.7')
    env.server.update()
    t.assertNil(string.find(env.transport.lastTo('10.0.0.7') or '', 'display_only', 1, true))
    t.assertEquals(env.server.onSkeleton(11, { id = '1-a', segments = { 0, 0, 5, 5 } }), 1)
    t.assertContains(env.transport.lastTo('10.0.0.7'), '"type":"skeleton"')
  end)
  t.it('still receives the telemetry of player 0 and can time out cleanly', function()
    local env = setup()
    env.transport.push(protocol.buildPingMessage(CODE, 2, 'Tablet', 'display'), '10.0.0.7')
    env.server.update()
    t.assertEquals(env.server.onTelemetry(11, { rpm = 900 }), 1)
    env.clock.advance(protocol.CLIENT_TIMEOUT_MS + 1)
    env.server.update()
    t.assertEquals(env.server.clients.count(), 0)
  end)
end)

t.describe('server: optional mods', function()
  local function sessions(env)
    local list = {}
    for _, s in ipairs(env.transport.sent) do
      if s.payload:find('"type":"session"', 1, true) then list[#list + 1] = s.payload end
    end
    return list
  end
  local function assigned(mods)
    local env = setup({ mods = mods })
    connect(env)
    local client = env.server.clients.get('10.0.0.2')
    env.server.onInputBindingsChanged({ ['vinput' .. client.deviceInst] = 0 })
    env.server.update()
    return env
  end
  t.it('knows the installed mods from the start, for the panel and the phones', function()
    local env = assigned({ fr17 = { active = true, modData = { tagid = 'MCSAUJ2PR' } } })
    local mods = env.server.state().optionalMods
    t.assertEquals(#mods, 4)
    t.assertEquals(mods[4].id, 'fr17')
    t.assertEquals(mods[4].state, 'enabled')
    t.assertEquals(mods[1].state, 'missing')
    t.assertContains(sessions(env)[1], '"fr17":"enabled"')
    t.assertContains(sessions(env)[1], '"cf26":"missing"')
  end)
  t.it('tells the panel and the phones when a mod is enabled or disabled', function()
    local env = assigned({ cf26 = { active = false, modData = { tagid = 'MSH2WZ9QV' } } })
    local before, published = #sessions(env), #env.states
    t.assertFalse(env.server.refreshOptionalMods())
    t.assertEquals(#sessions(env), before)
    env.mods.cf26.active = true
    t.assertTrue(env.server.refreshOptionalMods())
    t.assertEquals(#sessions(env), before + 1)
    t.assertContains(sessions(env)[#sessions(env)], '"cf26":"enabled"')
    t.assertTrue(#env.states > published)
    t.assertEquals(env.states[#env.states].optionalMods[3].state, 'enabled')
  end)
end)

t.describe('server: app and mod versions', function()
  local function phoneWithApp(appVersion, modVersion)
    local saved = serverModule.VERSION
    serverModule.VERSION = modVersion
    local env = setup()
    env.transport.push(protocol.buildPingMessage(CODE, 2, 'Pixel', 'controller', appVersion), '10.0.0.2')
    env.server.update()
    local phone = env.server.state().phones[1]
    serverModule.VERSION = saved
    return phone
  end
  t.it('tells the in-game panel which side is older', function()
    t.assertEquals(phoneWithApp('0.0.4', '0.0.5-0.39').update, 'app')
    t.assertEquals(phoneWithApp('0.0.6', '0.0.5-0.39').update, 'mod')
    t.assertEquals(phoneWithApp('0.0.6', '0.0.5-0.39').appVersion, '0.0.6')
  end)
  t.it('says nothing when they match or for apps that do not send their version', function()
    t.assertNil(phoneWithApp('0.0.5', '0.0.5-0.39').update)
    t.assertNil(phoneWithApp(nil, '0.0.5-0.39').update)
  end)
end)
